img_height, img_width = 369, 496

training_directory = path + '/training_small_full'
validation_directory = path + '/validation_small'

epochs = 10
batch_size = 28

if K.image_data_format() == 'channels_first':
    input_shape = (3, img_width, img_height)
else:
    input_shape = (img_width, img_height, 3)

model = keras.Sequential()

#
model.add(Conv2D(input_shape=input_shape, filters=32, kernel_size=(3,3), activation="relu"))
model.add(MaxPooling2D(pool_size=(2,2)))

model.add(Conv2D(filters=32,kernel_size=(3,3), activation="relu"))
model.add(MaxPooling2D(pool_size=(2,2)))


model.add(Conv2D(filters=64, kernel_size=(3,3), activation="relu"))
model.add(MaxPooling2D(pool_size=(2,2)))

model.add(Conv2D(filters=64, kernel_size=(3,3), activation="relu"))
model.add(MaxPooling2D(pool_size=(2,2)))

model.add(Conv2D(filters=64,kernel_size=(3,3), activation="relu"))
model.add(MaxPooling2D(pool_size=(2,2)))

model.add(Conv2D(filters=128, kernel_size=(3,3), activation="relu"))
model.add(MaxPooling2D(pool_size=(2,2)))


#
model.add(Flatten())
model.add(Dense(128))
model.add(Activation('relu'))

# Classifying the data
model.add(Dropout(0.5))
model.add(Dense( len( labelledClasses)))
model.add(Activation('sigmoid'))

model.compile(optimizer=keras.optimizers.Adam(), loss='categorical_crossentropy', metrics=['accuracy'])

model3 = keras.Sequential()
