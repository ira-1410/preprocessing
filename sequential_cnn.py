"""Prepare the Data"""

labelledClassesNames = [ dI for dI in listdir( f'{path}/training_small_full' ) ]
labelledClasses = {}

for className in labelledClassesNames:

    trainingPath = f'{path}/training_small_full/' + className
    validationPath = f'{path}/validation_small/' + className

    labelledClasses[className] = {}
    labelledClasses[className]['training'] = len( [ f for f in listdir( trainingPath ) if isfile( join ( trainingPath, f ) ) ] )
    labelledClasses[className]['validation'] = len( [ f for f in listdir( validationPath ) if isfile( join ( validationPath, f ) ) ] )

labelledClasses

img = cv.imread(path + '/training_small_full/garage rock/Welcome To Japan [IZg4rz3cIDc]1.png')
